export function listChemistryModuleIds(kind: "learn" | "lab"): string[] {
  const list = kind === "learn" ? CHEMISTRY_LEARN_MODULES : CHEMISTRY_LAB_MODULES;
  return list.map((m) => m.id);
}

export function getLocalChemistryModule(kind: "learn" | "lab", id: string): ModuleDetail | null {
  const list = kind === "learn" ? CHEMISTRY_LEARN_MODULES : CHEMISTRY_LAB_MODULES;
  return list.find((m) => m.id === id) ?? null;
}
